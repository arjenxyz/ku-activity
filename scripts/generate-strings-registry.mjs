#!/usr/bin/env node
/**
 * Generates src/lib/i18n/strings-registry.ts from json/src JSON files.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'json', 'src');
const OUT_FILE = path.join(ROOT, 'src', 'lib', 'i18n', 'strings-registry.ts');

const CONTENT_LOCALES = [
  'tr',
  'en',
  'zh',
  'hi',
  'es',
  'fr',
  'ar',
  'bn',
  'pt',
  'ru',
  'ur',
  'id',
  'de',
  'ja',
  'hu',
];

function walkJsonFiles(dir, base = '') {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkJsonFiles(full, rel));
    } else if (entry.name.endsWith('.json')) {
      files.push(rel.replace(/\\/g, '/').replace(/\.json$/, ''));
    }
  }
  return files.sort();
}

function toImportVar(key) {
  return `m_${key.replace(/[^a-zA-Z0-9]/g, '_')}`;
}

function jsonImportPath(locale, key) {
  if (locale === 'tr') return `@json/src/${key}.json`;
  return `@json/${locale}/src/${key}.json`;
}

function main() {
  const keys = walkJsonFiles(SRC_DIR);
  const imports = [];
  const registryEntries = [];

  for (const key of keys) {
    const bundleParts = [];
    for (const locale of CONTENT_LOCALES) {
      const varName = `${toImportVar(key)}_${locale}`;
      imports.push(`import ${varName} from '${jsonImportPath(locale, key)}';`);
      bundleParts.push(`${locale}: ${varName}`);
    }
    registryEntries.push(`  '${key}': { ${bundleParts.join(', ')} },`);
  }

  const content = `/* eslint-disable @typescript-eslint/no-explicit-any */
// AUTO-GENERATED by scripts/generate-strings-registry.mjs — do not edit manually

import type { Locale } from './locale';
import { pickStrings, type LocaleBundle } from './pickStrings';

${imports.join('\n')}

export const STRINGS_REGISTRY = {
${registryEntries.join('\n')}
} as const;

export type StringRegistryKey = keyof typeof STRINGS_REGISTRY;
export type StringModule = (typeof STRINGS_REGISTRY)[StringRegistryKey]['tr'];

export function getRegistryStrings<K extends StringRegistryKey>(
  key: K,
  locale: Locale
): (typeof STRINGS_REGISTRY)[K]['tr'] {
  const bundle = STRINGS_REGISTRY[key] as LocaleBundle<(typeof STRINGS_REGISTRY)[K]['tr']>;
  return pickStrings(locale, bundle);
}
`;

  fs.writeFileSync(OUT_FILE, content);
  console.log(`Generated ${OUT_FILE} with ${keys.length} entries × ${CONTENT_LOCALES.length} locales.`);
}

main();
